#!/usr/bin/env node
/**
 * Fails if `src/lib/database.types.ts` has drifted from the live schema.
 *
 * Schema changes here go straight to the live project (remote-only, see
 * CLAUDE.md) and the committed types are a hand-run snapshot. Nothing links the
 * two, so a migration applied without regenerating leaves every
 * `createClient<Database>()` type-checking queries against a schema that no
 * longer exists — including the price-masked owner views, where the types are
 * carrying a security-relevant guarantee. The failure mode is silent and looks
 * exactly like safety, which is the same shape as the anon grant that went
 * unnoticed for four days.
 *
 * Uses the Management API endpoint the Supabase MCP `generate_typescript_types`
 * tool calls, rather than `supabase gen types` via the CLI, so the bytes are
 * generated by the same code that produced the committed file. Going through
 * the CLI would add a version-skew failure that looks identical to real drift.
 *
 * Needs SUPABASE_ACCESS_TOKEN — a personal access token from
 * https://supabase.com/dashboard/account/tokens. This is NOT the service-role
 * key: it is an account-level token, so keep it to CI secrets.
 */

import { readFileSync } from 'node:fs'

const TYPES_FILE = 'src/lib/database.types.ts'
const PROJECT_REF = process.env.SUPABASE_PROJECT_REF ?? 'pjkddahrjjqblexxhaef'
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN

/** The committed file carries a hand-written header; generated content starts here. */
const GENERATED_MARKER = 'export type Json ='

function fail(message) {
  console.error(`\n✗ ${message}\n`)
  process.exit(1)
}

if (!TOKEN) {
  fail(
    'SUPABASE_ACCESS_TOKEN is not set.\n' +
      '  Create one at https://supabase.com/dashboard/account/tokens and export it,\n' +
      '  or set it as a repository secret so CI can run this check.',
  )
}

const res = await fetch(
  `https://api.supabase.com/v1/projects/${PROJECT_REF}/types/typescript`,
  { headers: { Authorization: `Bearer ${TOKEN}` } },
)

if (!res.ok) {
  fail(`Management API returned HTTP ${res.status}: ${await res.text()}`)
}

const { types: live } = await res.json()
if (typeof live !== 'string' || !live.includes(GENERATED_MARKER)) {
  fail('Management API response did not contain generated types.')
}

const committedFile = readFileSync(TYPES_FILE, 'utf8')
const markerAt = committedFile.indexOf(GENERATED_MARKER)
if (markerAt === -1) {
  fail(`${TYPES_FILE} does not contain "${GENERATED_MARKER}" — is it still the generated file?`)
}

// Compare only the generated portion; the header above it is ours to write.
const committed = committedFile.slice(markerAt).trimEnd()
const expected = live.slice(live.indexOf(GENERATED_MARKER)).trimEnd()

if (committed === expected) {
  console.log(`✓ ${TYPES_FILE} matches the live schema of ${PROJECT_REF}`)
  process.exit(0)
}

// Show the first differing lines rather than the whole file.
const a = committed.split('\n')
const b = expected.split('\n')
const diffs = []
for (let i = 0; i < Math.max(a.length, b.length) && diffs.length < 20; i++) {
  if (a[i] !== b[i]) {
    diffs.push(`  line ${i + 1}\n    committed: ${a[i] ?? '(missing)'}\n    live:      ${b[i] ?? '(missing)'}`)
  }
}

fail(
  `${TYPES_FILE} is out of date with the live schema.\n\n` +
    diffs.join('\n') +
    (a.length !== b.length ? `\n  (committed ${a.length} lines, live ${b.length})` : '') +
    '\n\n  Regenerate it with the Supabase MCP `generate_typescript_types` tool for ' +
    `project ${PROJECT_REF} and commit the result.`,
)
